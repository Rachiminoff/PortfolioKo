-- Run this in the Supabase SQL Editor.
-- The page has no manga CRUD controls; it writes only AniList metadata cache columns.
create table if not exists public.manga_masterlist (
  id bigint generated by default as identity primary key,
  title text not null,
  anilist_id bigint unique,
  mal_id bigint unique,
  total_volumes integer,
  total_chapters integer,
  read_volumes integer not null default 0,
  read_chapters integer not null default 0,
  score numeric(3,1),
  status text not null default 'Plan to Read'
    check (status in ('Reading', 'Completed', 'On-Hold', 'Dropped', 'Plan to Read')),
  start_date date,
  finish_date date,
  tags text[] not null default '{}',
  comments text,
  cover_url text,
  anilist_metadata jsonb,
  anilist_fetched_at timestamptz,
  anilist_fetch_status text not null default 'pending' check (anilist_fetch_status in ('pending', 'ok', 'not_found')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint manga_masterlist_nonnegative_progress check (
    (total_volumes is null or total_volumes >= 0) and
    (total_chapters is null or total_chapters >= 0) and
    read_volumes >= 0 and read_chapters >= 0 and
    (score is null or score between 0 and 10)
  )
);

-- Additive migration for projects that already created the table before metadata caching.
alter table public.manga_masterlist add column if not exists anilist_metadata jsonb;
alter table public.manga_masterlist add column if not exists anilist_fetched_at timestamptz;
alter table public.manga_masterlist add column if not exists anilist_fetch_status text not null default 'pending';

create index if not exists manga_masterlist_title_idx on public.manga_masterlist (title);
create index if not exists manga_masterlist_status_idx on public.manga_masterlist (status);

alter table public.manga_masterlist enable row level security;
-- Personal, read-only page: anonymous/authenticated clients may read, but cannot mutate.
drop policy if exists "manga masterlist read access" on public.manga_masterlist;
create policy "manga masterlist read access"
  on public.manga_masterlist for select to anon, authenticated using (true);
-- No INSERT or DELETE policies are created. Reading data is not browser-writable; manage it in Supabase Studio.

-- Remove broad UPDATE grants first, then allow writes to cache columns only.
revoke update on public.manga_masterlist from anon, authenticated, public;
grant update (anilist_metadata, anilist_fetched_at, anilist_fetch_status)
  on public.manga_masterlist to anon, authenticated;
drop policy if exists "manga metadata cache update" on public.manga_masterlist;
create policy "manga metadata cache update"
  on public.manga_masterlist for update to anon, authenticated
  using (true) with check (true);
